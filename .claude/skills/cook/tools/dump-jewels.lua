## Authoring and measuring historics headless

```
Rarity: UNIQUE
Lethal Pride
Timeless Jewel
Limited to: 1 Historic
Radius: Large
Implicits: 0
Commanded leadership over 12000 warriors under Kaom
Passives in radius are Conquered by the Karui
Historic
```

Write the seed line CONCRETE (validate checks it in range against the current variants).
Socket, refresh, then read `node.conqueredBy` / `node.sd` off the spec - conquests are
recomputed inside `BuildAllDependsAndPaths`, so they are always current. Seed hunting is
a sweep: loop seeds, edit the one number in the raw, re-parse, refresh, measure - or
call `data.readLUT(seed, nodeId, jewelType)` directly for a single node's outcomes
(types 1-6 in `data.timelessJewelTypes` order).

The LUTs ship as zlib streams (`src/Data/TimelessJewelData/*.zip*`, multi-part files
concatenated). HeadlessWrapper stubs `Inflate`/`Deflate` to return `""`; the kitchen's
`pob.lua` rebinds both through `runtime/zlib1.dll`, without which every notable reports
`Missing LUT` and abyss jewels CRASH the calc on socketing. First legion-jewel load also
rewrites the `.bin` caches the GUI uses; abyss data (~28 MB compressed each) is inflated
once per process and cached in memory only.
