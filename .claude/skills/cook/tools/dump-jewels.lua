------------------------------------------------------------------ parse unique jewels
local knownProps = {
	["League"] = true, ["Source"] = true, ["Radius"] = true, ["Limited to"] = true,
	["Requires Level"] = true, ["Selected Variant"] = true, ["Selected Alt Variant"] = true,
	["Selected Alt Variant Two"] = true, ["Has Alt Variant"] = true, ["Has Alt Variant Two"] = true,
	["Item Level"] = true, ["LevelReq"] = true, ["Upgrade"] = true, ["Implicits"] = true,
}
local function parseUnique(raw)
	local u = { props = {}, variants = {}, mods = {} }
	local first = true
	for line in raw:gmatch("[^\r\n]+") do
		if first then u.name = line; first = false
		elseif not u.base and not line:match(":") then u.base = line
		else
			local variant = line:match("^Variant: (.+)$")
			local prop, val = line:match("^([%a][%w%s]-): (.+)$")
			if variant then table.insert(u.variants, variant)
			elseif prop and knownProps[prop] then u.props[prop] = val
			else table.insert(u.mods, line) end
		end
	end
	u.text = table.concat(u.mods, "\n")
	return u
end
local jewels = {}
for _, raw in ipairs(data.uniques.jewel or {}) do
	table.insert(jewels, parseUnique(raw))
end

