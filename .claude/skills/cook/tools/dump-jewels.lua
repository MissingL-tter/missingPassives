print([[
# Radius and rule-changing jewels

Obtainable uniques that transform, re-grant or re-wire existing nodes (plain "per X in
Radius" counters just READ the tree and are excluded). Multi-variant lines are shown as
the variant list.
]])

local groups = {
	{ key = "alsoGrant", title = "Radius auras - every allocated passive in radius also grants the stat",
	  match = function(t) return t:match("in Radius also grant") end },
	{ key = "transform", title = "Transformers - modifiers in radius become other modifiers",
	  match = function(t) return t:match("Transformed") end },
	{ key = "regrant", title = "Effect rewriters - nodes in radius grant more, less or nothing",
	  match = function(t) return (t:match("increased Effect of") and t:match("Radius"))
		or t:match("grant nothing") or t:match("Unallocated Small Passive") end },
	{ key = "rewire", title = "Allocation re-wiring - allocate without connection",
	  match = function(t) return t:match("can be Allocated without being connected")
		or t:match("Passives in Radius of") end },
	{ key = "position", title = "Socket-position jewels - scale on where the socket sits",
	  match = function(t) return t:match("connects to a class' starting location")
		or t:match("your Class' starting location") end },
}
local used = {}
for _, g in ipairs(groups) do
	local rows = {}
	for _, u in ipairs(jewels) do
		if not used[u.name] and not (u.props["Source"] or ""):match("No longer obtainable")
		   and u.props["Limited to"] ~= "1 Historic" and g.match(u.text) then
			used[u.name] = true
			table.insert(rows, u)
		end
	end
	if #rows > 0 then
		table.sort(rows, function(a, b) return a.name < b.name end)
		print("## " .. g.title .. "\n")
		for _, u in ipairs(rows) do
			local bits = {}
			if u.props["Radius"] then table.insert(bits, "radius " .. u.props["Radius"]) end
			if u.props["Limited to"] then table.insert(bits, "limit " .. u.props["Limited to"]) end
			print(string.format("**%s** (%s%s)", u.name, u.base,
				#bits > 0 and ", " .. table.concat(bits, ", ") or ""))
			local variantLines, plain = {}, {}
			for _, m in ipairs(u.mods) do
				local v = m:gsub("^{variant:[%d,]+}", "")
				if v ~= "Corrupted" and v ~= "Passage" and v ~= "Historic" then
					if v ~= m then table.insert(variantLines, v)
					elseif not m:match("^{") then table.insert(plain, v) end
				end
			end
			for _, m in ipairs(plain) do print("- " .. m) end
			if #variantLines > 0 then
				print("- one of: " .. table.concat(variantLines, " / "))
			end
			print("")
		end
	end
end

