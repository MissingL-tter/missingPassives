print([[
# Historic jewels

Seed-based node transformation. **The whole character gets ONE historic** - all eleven
carry `Limited to: 1 Historic`. PoB enforces it silently: the first-socketed jewel wins,
every later one gets `item.jewelData.limitDisabled = true` and contributes nothing.
Check that flag when a historic seems dead.

## The six radius timeless jewels

Socket in any tree socket; every node in Large radius is conquered. What happens then
(PassiveSpec.lua:1191+, verified headless):

- **Keystones** become the conqueror's keystone - fixed by VARIANT, the seed never
  matters. The keystone is the parenthesised name in the tables below.
- **Notables** roll on the seed: replaced by a legion notable or given legion additions.
  Sweep seeds by measuring; there is no shortcut reasoning.
- **Small passives** are deterministic per legion:

| legion | small passives | attribute smalls |
|---|---|---|
| Karui (Lethal Pride) | keep stats, +4 Strength | +2 Strength |
| Maraketh (Brutal Restraint) | keep stats, +4 Dexterity | +2 Dexterity |
| Kalguur (Heroic Tragedy) | keep stats, +2% increased Ward | +1% Ward |
| Templar (Militant Faith) | keep stats, +5 Devotion | replaced by +10 Devotion node |
| Eternal (Elegant Hubris) | REPLACED BY BLANK - stats wiped | blanked too |
| Vaal (Glorious Vanity) | rerolled from seed - anything | rerolled |
]])

local timeless = {}
local abyssHist = {}
for _, u in ipairs(jewels) do
	if u.props["Limited to"] == "1 Historic" then
		if u.base == "Timeless Jewel" then table.insert(timeless, u)
		else table.insert(abyssHist, u) end
	end
end
table.sort(timeless, function(a, b) return a.name < b.name end)
table.sort(abyssHist, function(a, b) return a.name < b.name end)

print("| jewel | legion | seed (item text) | conquerors -> keystone granted |")
print("|---|---|---|---|")
for _, u in ipairs(timeless) do
	local legion = (u.text:match("Conquered by the ([%a ]+)") or "?"):gsub("%s+$", "")
	local seed = u.text:match("%((%d+%-%d+)%)")
	local cq = {}
	for _, v in ipairs(u.variants) do
		local who, keystone = v:match("^([%a]+) %((.+)%)$")
		if who then
			if v:match("Pre %d") then
				table.insert(cq, who .. " -> " .. keystone:gsub("%) %(Pre.*", "") .. " LEGACY, not obtainable")
			else
				table.insert(cq, who .. " -> " .. keystone)
			end
		end
	end
	print(string.format("| %s | %s | %s | %s |", u.name, legion or "?", seed or "?",
		table.concat(cq, "; ")))
end
